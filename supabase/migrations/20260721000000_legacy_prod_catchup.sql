-- creditorderstatus: prod still has the original ('pending','paid','cancelled').
-- Dev's is ('in_progress','paid','complete','void','on_hold'). Postgres cannot drop
-- enum values, so swap the type. Created complete — unlike the original lineage,
-- which added 'on_hold' via ALTER TYPE ADD VALUE and therefore needed a second
-- transaction before any index could reference it.
do $$
begin
    if not exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid
                   where t.typname = 'creditorderstatus' and e.enumlabel = 'in_progress') then
        create type creditorderstatus_v2 as enum ('in_progress', 'paid', 'complete', 'void', 'on_hold');
        alter table credit_orders alter column status drop default;
        -- Any index whose predicate names an old label pins the column to the old
        -- type. uq_credit_orders_one_pending_per_pack is a legacy-only index (dev
        -- has no equivalent) superseded by uq_credit_orders_one_open_per_tenant.
        drop index if exists uq_credit_orders_one_open_per_tenant;
        drop index if exists uq_credit_orders_one_pending_per_pack;
        alter table credit_orders alter column status type creditorderstatus_v2
            using (case status::text
                when 'pending'   then 'in_progress'
                when 'paid'      then 'paid'
                when 'cancelled' then 'void'
                else 'in_progress'
            end)::creditorderstatus_v2;
        alter table credit_orders alter column status set default 'in_progress';
        drop type creditorderstatus;
        alter type creditorderstatus_v2 rename to creditorderstatus;
    end if;
end $$;

-- ── 3. admin_users: email is the login handle, renamed to username ─────────────
-- Rename, not add+drop: dev has no `email` column, and prod's is NOT NULL, so
-- leaving it would reject every insert the current app code makes.
do $$
begin
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = 'admin_users' and column_name = 'email') then
        alter table admin_users rename column email to username;
        alter index if exists uq_admin_user_email_active rename to uq_admin_user_username_active;
    end if;
end $$;

