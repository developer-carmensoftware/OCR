-- Catch-up: bring the legacy production DB onto the Supabase-CLI schema lineage.
--
-- Context. Production (project lhlncsjqxttcdegkqvid) was built by the old custom
-- runner in backend/app/migrations.py, tracked in public.schema_migrations, and
-- stopped at 217_soft_delete_stray_monthly_quota (2026-06-29). The CLI lineage that
-- replaced it (20260615000000_v1_baseline.sql onward) was written for a greenfield
-- project — its own header says "Greenfield: no production data" — so `supabase db
-- push` against prod fails immediately on `create table plans`.
--
-- This migration is the bridge. It is NOT a replay of migrations 0002..20260717;
-- it was generated by diffing the dev project (ycykjisvvrrbgeiirqre, all 42 CLI
-- migrations applied) against prod, so the enum churn (20260622030000 →
-- 20260623000200 → 20260701070739) and the four rounds of cron-SQL fixes collapse
-- into their end state.
--
-- Run order: apply this, then `supabase migration repair --status applied` for every
-- version from 20260615000000 through 20260717000000, after which prod is a normal
-- CLI-managed database and `supabase db push` works.
--
-- DEFERRED — deliberately not in this file (see the report accompanying it):
--   * Partitioning of audit_logs / llm_usage_logs / outbound_call_logs /
--     performance_logs, and the pg_partman extension + partman-maintain cron job.
--     Those four tables hold live rows (667 / 371 / 1980 / 3618); converting a
--     populated table to a partitioned one is a copy-and-swap that wants a
--     maintenance window, not a migration that runs behind a deploy.
--   * public.schema_migrations (the legacy tracker) is left in place as a record of
--     how prod got here. Drop it once this migration is confirmed good.

